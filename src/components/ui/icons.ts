export function refreshIcons(root: ParentNode = document): void {
  createIcons({ icons, root: root as Element | Document | DocumentFragment });
}

export function icon(name: string, className = ''): string {
  const safeClass = className.replace(/"/g, '');
  return `<i data-lucide="${name}"${safeClass ? ` class="${safeClass}"` : ''} aria-hidden="true"></i>`;
}
